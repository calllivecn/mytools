#!/usr/bin/env python3
"""Flask upload/download speed-test API.

Upload:
    POST <prefix>/api/upload
    The request body is read and discarded. Nothing is saved on the server.

Download:
    GET <prefix>/api/download?size=<MB>
    Streams generated bytes. Without "size" the stream never ends.
    The returned file name is always "speedtest.bin".

The optional --prefix makes the API work behind an Nginx location such as
/speedtest/ without stripping the prefix.
"""

import argparse
import os
import re
from decimal import Decimal, DecimalException
from urllib.parse import quote

from flask import (
    Blueprint,
    Flask,
    Response,
    jsonify,
    request,
    stream_with_context,
)
from werkzeug.exceptions import HTTPException, RequestEntityTooLarge

MB = 1024 * 1024
CHUNK_SIZE = 64 * 1024

# Fixed name returned by the download API.
DOWNLOAD_FILENAME = "speedtest.bin"

# Random data is not compressible, so an Nginx gzip setting cannot distort the
# speed test. One block is generated per process and reused.
DATA_BLOCK = os.urandom(CHUNK_SIZE)


def json_error(message, status):
    return jsonify(ok=False, error=message), status


def normalize_prefix(value):
    """Normalize a URL prefix to "" or "/something" (no trailing slash)."""
    value = (value or "").strip()
    if value in ("", "/"):
        return ""
    if "://" in value or "?" in value or "#" in value:
        raise ValueError("prefix must be a URL path, for example /speedtest")
    value = "/" + value.strip("/")
    return re.sub(r"/+", "/", value)


def parse_size_mb(value):
    """Return bytes for a "size" query value in MB. None/empty means endless."""
    if value is None or not value.strip():
        return None
    try:
        size = Decimal(value.strip())
        if not size.is_finite() or size <= 0:
            raise ValueError("size must be greater than 0 MB")
        limit = int(size * MB)
    except (DecimalException, ValueError, OverflowError):
        raise ValueError("size must be a positive number in MB, for example size=100")
    if limit <= 0:
        raise ValueError("size is too small")
    return limit


def generate_data(limit):
    """Yield generated bytes, forever when limit is None."""
    remaining = limit
    while remaining is None or remaining > 0:
        chunk_size = CHUNK_SIZE if remaining is None else min(CHUNK_SIZE, remaining)
        yield DATA_BLOCK[:chunk_size]
        if remaining is not None:
            remaining -= chunk_size


def content_disposition(filename):
    fallback = re.sub(r'[\x00-\x1f\x7f"\\]', "_", filename)
    return (
        f'attachment; filename="{fallback}"; '
        f"filename*=UTF-8''{quote(filename, safe='')}"
    )


def create_app(prefix=None, max_upload_mb=None):
    if prefix is None:
        prefix = os.environ.get("PREFIX", "")
    prefix = normalize_prefix(prefix)

    if max_upload_mb is None:
        max_upload_mb = int(os.environ.get("MAX_UPLOAD_MB", "0"))

    app = Flask(__name__)
    if max_upload_mb > 0:
        app.config["MAX_CONTENT_LENGTH"] = max_upload_mb * MB
    app.config["MAX_UPLOAD_MB"] = max_upload_mb
    app.config["PREFIX"] = prefix

    api = Blueprint("api", __name__, url_prefix=prefix or None)

    @api.get("/")
    def index():
        return jsonify(
            ok=True,
            prefix=prefix,
            endpoints={
                "upload": f"{prefix}/api/upload",
                "download": f"{prefix}/api/download?size=<MB>",
                "download_unlimited": f"{prefix}/api/download",
            },
        )

    @api.post("/api/upload")
    def upload():
        received = 0
        try:
            while True:
                chunk = request.stream.read(CHUNK_SIZE)
                if not chunk:
                    break
                received += len(chunk)
        except OSError as exc:
            return json_error(f"failed to read request body: {exc}", 400)

        return jsonify(
            ok=True,
            filename="upload.bin",
            received_bytes=received,
        )

    @api.get("/api/download")
    def download():
        try:
            limit = parse_size_mb(request.args.get("size"))
        except ValueError as exc:
            return json_error(str(exc), 400)

        response = Response(
            stream_with_context(generate_data(limit)),
            mimetype="application/octet-stream",
            direct_passthrough=True,
        )
        response.headers["Content-Disposition"] = content_disposition(
            DOWNLOAD_FILENAME
        )
        response.headers["Cache-Control"] = "no-store"
        response.headers["X-Content-Type-Options"] = "nosniff"
        if limit is None:
            response.headers["X-Download-Bytes"] = "unlimited"
        else:
            response.headers["Content-Length"] = str(limit)
            response.headers["X-Download-Bytes"] = str(limit)
        return response

    app.register_blueprint(api)

    @app.errorhandler(RequestEntityTooLarge)
    def upload_too_large(error):
        return (
            jsonify(
                ok=False,
                error="uploaded data is too large",
                max_upload_mb=app.config.get("MAX_UPLOAD_MB"),
            ),
            413,
        )

    @app.errorhandler(HTTPException)
    def handle_http_error(error):
        if request.path.startswith(f"{prefix}/api/"):
            return json_error(error.description, error.code)
        return error

    return app


def main():
    parser = argparse.ArgumentParser(description="Flask upload/download speed-test API")
    parser.add_argument(
        "--host", default=os.environ.get("HOST", "0.0.0.0"), help="listen address"
    )
    parser.add_argument(
        "--port", type=int, default=int(os.environ.get("PORT", "8000")), help="port"
    )
    parser.add_argument(
        "--prefix",
        default=os.environ.get("PREFIX", ""),
        help="URL path prefix when mounted behind Nginx, for example /speedtest",
    )
    parser.add_argument("--debug", action="store_true", help="enable Flask debug mode")
    args = parser.parse_args()

    app = create_app(args.prefix)
    app.run(host=args.host, port=args.port, debug=args.debug, threaded=True)


if __name__ == "__main__":
    main()
